#!/usr/bin/env python3
"""Generates lib/markdown/mermaid_theme_clone.dart.

mermaid_core's MermaidTheme has no copyWith for chart palettes (pie, cScale, sequence
actors, ...). This writes a helper that copies every field of a preset and replaces the
colours we pass in by name. Re-run after upgrading mermaid_core:

    python3 tool/gen_mermaid_theme_clone.py
"""
import glob, os, re, sys

pkg = sorted(glob.glob(os.path.expanduser('~/.pub-cache/hosted/pub.dev/mermaid_core-*')))[-1]
version = os.path.basename(pkg).split('-', 1)[1]
src = open(f'{pkg}/lib/src/theme/theme.dart').read()
start = src.index('class MermaidTheme {')
body = src[start:]
colors = re.findall(r'^\s+final Color (\w+);', body, re.M)
assert colors, 'no colour fields found'

lines = [
    '// GENERATED by tool/gen_mermaid_theme_clone.py from mermaid_core %s. Do not edit.' % version,
    '// ignore_for_file: prefer_const_constructors',
    "import 'package:mermaid_core/mermaid_core.dart' as m;",
    '',
    '/// Copy of [base] with the named colours replaced (keys are MermaidTheme field names).',
    'm.MermaidTheme cloneMermaidTheme(',
    '  m.MermaidTheme base, {',
    '  Map<String, m.Color> colors = const {},',
    '  List<m.Color>? xyChartPlotColorPalette,',
    '  String? fontFamily,',
    '  double? fontSize,',
    '}) {',
    '  m.Color c(String name, m.Color fallback) => colors[name] ?? fallback;',
    '  return m.MermaidTheme(',
    '    fontFamily: fontFamily ?? base.fontFamily,',
    '    fontSize: fontSize ?? base.fontSize,',
    '    xyChartPlotColorPalette: xyChartPlotColorPalette ?? base.xyChartPlotColorPalette,',
]
for n in colors:
    lines.append(f"    {n}: c('{n}', base.{n}),")
lines += ['  );', '}', '']
open('lib/markdown/mermaid_theme_clone.dart', 'w').write('\n'.join(lines))
print(f'wrote {len(colors)} colour fields for mermaid_core {version}')
